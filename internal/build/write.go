package build

import (
	"bytes"
	"crypto/sha256"
	"encoding/hex"
	"errors"
	"fmt"
	"io/fs"
	"os"
	"path/filepath"
	"sort"
	"strconv"
	"strings"
)

// Marker is the file Write drops in every output directory it owns. Its
// presence is what lets a later Write treat the directory's visible contents
// as disposable; a non-empty directory without it is refused, so a
// misconfigured output path can never wipe user files. It doubles as the
// manifest of preserve-mode files (see File.Preserve and manifest).
// Dot-prefixed, so the module walker never reads it back as input.
const Marker = ".kastorbuild"

// markerVersion is the record format Write writes and understands. A marker
// claiming a higher version came from a newer kastor whose records this build
// cannot interpret, which is refused rather than guessed at.
const markerVersion = 1

// SidecarSuffix ends the name of the copy of a generated stub Write leaves
// beside a file the user has implemented, when the spec has moved the stub out
// from under them. The suffix is the whole trick: it makes the file inert to
// the toolchain that compiles the directory (no .py, no .ts) while leaving it
// in plain sight, since a sidecar is the one artifact here the user is meant to
// act on. removeStale skips these by suffix; Write removes one only when the
// stub it belongs to is settled. Exported for diagnostics that name it.
const SidecarSuffix = ".kastor-new"

const markerHeader = `# Generated by kastor build. Do not edit files in this directory.
# The records below are how kastor tells its own generated stubs apart from
# files you have implemented; deleting them risks losing your edits.
`

// Report is what Write did that the user needs to hear about. Both fields
// concern preserve-mode files only — everything else is regenerated silently.
// Paths are slash-separated and relative to the output directory, in the same
// canonical order Run gives the file list.
type Report struct {
	// Superseded lists user-implemented files whose generated stub changed:
	// the file was kept and the new stub written to its sidecar.
	Superseded []Change
	// Orphaned lists user-implemented files the spec no longer generates.
	// They were kept rather than removed; deleting them is the user's call.
	Orphaned []string
}

// Change is one user-implemented file that the spec has moved on from, paired
// with the sidecar holding the stub it would be generated as today.
type Change struct {
	Path    string
	Sidecar string
}

// Write syncs files into the output directory dir: changed files are
// written, unchanged files are left untouched (mtimes preserved), and
// visible files from a previous build that are no longer generated are
// removed, along with directories that emptied. The directory is created if
// missing.
//
// Write only ever touches paths it can name: the generated files, the marker,
// and the sidecar of a generated stub. Everything else in the directory is the
// user's. Hidden (dot-prefixed) entries are the strong form of that rule —
// Write neither reads nor removes them, and the only hidden path it writes is
// the marker — while visible files it did not generate are removed as stale,
// which is what makes the marker's ownership check in claim the safeguard it
// is.
//
// Files marked Preserve are the exception to all of that: kastor owns such a
// file only until the user edits it (see syncStub). The returned Report names
// the ones that needed the user's attention.
func Write(dir string, files []File) (*Report, error) {
	for _, f := range files {
		if err := f.validate(); err != nil {
			return nil, fmt.Errorf("writing %s: %w", dir, err)
		}
	}

	prev, err := claim(dir)
	if err != nil {
		return nil, err
	}

	rep := &Report{}
	next := newManifest()
	keep := map[string]bool{}
	for _, f := range files {
		rel := filepath.FromSlash(f.Path)
		keep[rel] = true
		if f.Preserve {
			if err := syncStub(dir, f, prev, next, rep); err != nil {
				return nil, fmt.Errorf("writing %s: %w", dir, err)
			}
			continue
		}
		if err := writeFile(filepath.Join(dir, rel), f.Data); err != nil {
			return nil, fmt.Errorf("writing %s: %w", dir, err)
		}
	}

	if err := removeStale(dir, keep, prev, next, rep); err != nil {
		return nil, fmt.Errorf("cleaning %s: %w", dir, err)
	}

	if err := writeFile(filepath.Join(dir, Marker), next.render()); err != nil {
		return nil, fmt.Errorf("writing %s: %w", dir, err)
	}
	return rep, nil
}

// claim makes dir safe to sync into: it creates the directory if needed,
// ensures the marker exists, and returns the records the last build left in
// it. A non-empty directory that has no marker was not produced by kastor
// build and is refused.
func claim(dir string) (*manifest, error) {
	if err := os.MkdirAll(dir, 0o755); err != nil {
		return nil, fmt.Errorf("creating output directory: %w", err)
	}

	markerPath := filepath.Join(dir, Marker)
	data, err := os.ReadFile(markerPath)
	if err == nil {
		man, err := parseManifest(data)
		if err != nil {
			return nil, fmt.Errorf("reading %s: %w", markerPath, err)
		}
		return man, nil
	}
	if !errors.Is(err, fs.ErrNotExist) {
		return nil, fmt.Errorf("reading %s: %w", markerPath, err)
	}

	entries, err := os.ReadDir(dir)
	if err != nil {
		return nil, fmt.Errorf("reading output directory: %w", err)
	}
	if len(entries) > 0 {
		return nil, fmt.Errorf("output directory %s is not empty and has no %s marker; refusing to overwrite it — remove the directory or point the target elsewhere", dir, Marker)
	}
	// Claim the directory before writing anything into it, so a build that
	// fails midway still leaves a directory the next build recognizes.
	if err := os.WriteFile(markerPath, newManifest().render(), 0o644); err != nil {
		return nil, err
	}
	return newManifest(), nil
}

// syncStub applies the preserve-mode contract for one generated stub: kastor
// writes the file while it is still kastor's — absent, or byte-identical to
// the stub the last build wrote — and never writes it again once the user has
// edited it. A spec change that lands under an edited file cannot be merged,
// so the fresh stub goes to a sidecar and the file is reported instead.
func syncStub(dir string, f File, prev, next *manifest, rep *Report) error {
	target := filepath.Join(dir, filepath.FromSlash(f.Path))
	fresh := hashBytes(f.Data)
	rec := prev.records[f.Path]

	existing, err := os.ReadFile(target)
	switch {
	case errors.Is(err, fs.ErrNotExist):
		// First build for this stub: nothing of the user's can be at risk.
		next.set(f.Path, fresh, owned)
		return writeFile(target, f.Data)
	case err != nil:
		return err
	}

	switch {
	case bytes.Equal(existing, f.Data):
		// Pristine: never touched, or edited and then reverted. The file already
		// is the current stub, so it is kastor's again and any sidecar is settled.
		next.set(f.Path, fresh, owned)
		return removeSidecar(dir, f.Path)
	case rec.state == owned && hashBytes(existing) == rec.stub:
		// Still the stub the last build wrote, so the spec moved and no user
		// code stands in the way: regenerate in place.
		next.set(f.Path, fresh, owned)
		if err := removeSidecar(dir, f.Path); err != nil {
			return err
		}
		return writeFile(target, f.Data)
	}

	// The file is the user's from here on: it is never written again, whatever
	// the spec does. Recording the fresh stub hash is what keeps the report
	// below a one-time event — the sidecar on disk is its durable half.
	next.set(f.Path, fresh, implemented)
	if rec.stub == fresh {
		// The stub the user last saw is the one the spec still generates.
		// Nothing to do, and nothing worth saying.
		return nil
	}

	sidecar := SidecarFor(f.Path)
	if err := writeFile(filepath.Join(dir, filepath.FromSlash(sidecar)), f.Data); err != nil {
		return err
	}
	rep.Superseded = append(rep.Superseded, Change{Path: f.Path, Sidecar: sidecar})
	return nil
}

// SidecarFor names the sidecar Write uses for a generated stub: the file's own
// name plus SidecarSuffix, in the same directory. Generators call it so the
// path they describe in stub comments cannot drift from the one Write uses.
func SidecarFor(file string) string {
	return file + SidecarSuffix
}

// removeSidecar drops a stub's sidecar once the stub and the file on disk
// agree again — the user reconciled, or reverted.
func removeSidecar(dir, file string) error {
	err := os.Remove(filepath.Join(dir, filepath.FromSlash(SidecarFor(file))))
	if err != nil && !errors.Is(err, fs.ErrNotExist) {
		return err
	}
	return nil
}

// removeStale deletes visible files under dir that are not in keep (paths
// relative to dir, in OS form), then prunes directories that emptied.
// Hidden entries and everything beneath them are skipped: they are the
// user's, and a directory holding one never counts as empty. Sidecars are
// skipped too — no build generates one, so "not generated" would otherwise
// delete the very message Write left for the user.
//
// A file the last build recorded as a stub is the one case where "no longer
// generated" is not enough to delete: if its contents have diverged from that
// record it holds the user's implementation of a tool the spec has dropped,
// which is kept and reported. Its record is kept too, so the file stays
// recognizable as the user's on every later build.
func removeStale(dir string, keep map[string]bool, prev, next *manifest, rep *Report) error {
	var dirs []string
	err := filepath.WalkDir(dir, func(path string, d fs.DirEntry, err error) error {
		if err != nil {
			return err
		}
		if strings.HasPrefix(d.Name(), ".") && path != dir {
			if d.IsDir() {
				return filepath.SkipDir
			}
			return nil
		}
		if d.IsDir() {
			if path != dir {
				dirs = append(dirs, path)
			}
			return nil
		}
		if strings.HasSuffix(d.Name(), SidecarSuffix) {
			return nil
		}
		rel, err := filepath.Rel(dir, path)
		if err != nil {
			return err
		}
		if keep[rel] {
			return nil
		}

		slash := filepath.ToSlash(rel)
		if rec, ok := prev.records[slash]; ok {
			sum, err := hashPath(path)
			if err != nil {
				return err
			}
			if rec.state != owned || sum != rec.stub {
				// The user's implementation of something the spec no longer
				// declares. Keep the file and its record, so it stays
				// recognizable as theirs, and report the handover on the way
				// into the orphaned state — which is where it stays.
				next.set(slash, rec.stub, orphaned)
				if rec.state != orphaned {
					rep.Orphaned = append(rep.Orphaned, slash)
				}
				return nil
			}
			// An untouched stub for a tool the spec dropped: ours to clean up,
			// sidecar and all.
			if err := removeSidecar(dir, slash); err != nil {
				return err
			}
		}
		return os.Remove(path)
	})
	if err != nil {
		return err
	}

	// Children sort after their parent, so deleting in reverse order prunes
	// bottom-up. Remove fails harmlessly on directories that still hold
	// files (including hidden ones).
	sort.Sort(sort.Reverse(sort.StringSlice(dirs)))
	for _, d := range dirs {
		_ = os.Remove(d)
	}
	return nil
}

// writeFile writes data to path, creating parent directories. An existing
// file with identical content is left untouched so file watchers and build
// caches downstream of the output directory only fire on real changes.
func writeFile(path string, data []byte) error {
	if existing, err := os.ReadFile(path); err == nil && bytes.Equal(existing, data) {
		return nil
	}
	if err := os.MkdirAll(filepath.Dir(path), 0o755); err != nil {
		return err
	}
	return os.WriteFile(path, data, 0o644)
}

// state is what has become of one preserve-mode file, and it is also the record
// of what the user has already been told about it: each report Write makes is
// the transition into a state, so a state that is already recorded is a report
// already delivered.
type state int

const (
	// owned: the file is still the stub Write put there, so Write may rewrite it.
	owned state = iota
	// implemented: the user has edited the file. Write never writes it again.
	implemented
	// orphaned: implemented, and the spec no longer generates it at all.
	orphaned
)

// keywords name the states in the marker, in state order.
var keywords = [...]string{"stub", "kept", "orphan"}

// record is the marker's memory of one preserve-mode file: which state it is
// in, and the stub Write last wrote there or last showed the user. Those two
// facts answer every question the contract asks — may this file be
// overwritten, has its stub changed since the user last saw one, and has the
// user already heard about it.
type record struct {
	stub  string
	state state
}

// manifest maps slash path → record for the preserve-mode files in one output
// directory.
type manifest struct {
	records map[string]record
}

func newManifest() *manifest {
	return &manifest{records: map[string]record{}}
}

func (m *manifest) set(p, stub string, s state) { m.records[p] = record{stub: stub, state: s} }

// render writes the marker body: the human-facing header, the version, then
// one record per preserve-mode file sorted by path, so the marker is as
// deterministic as the generated files around it.
func (m *manifest) render() []byte {
	var b strings.Builder
	b.WriteString(markerHeader)
	fmt.Fprintf(&b, "kastorbuild %d\n", markerVersion)

	paths := make([]string, 0, len(m.records))
	for p := range m.records {
		paths = append(paths, p)
	}
	sort.Strings(paths)
	for _, p := range paths {
		rec := m.records[p]
		fmt.Fprintf(&b, "%s %s %s\n", keywords[rec.state], rec.stub, p)
	}
	return []byte(b.String())
}

// parseManifest reads marker records. Anything it cannot make sense of — a
// marker from before records existed, or one that has been hand-edited —
// yields an empty manifest rather than an error: with no records every
// existing file looks like the user's, which is the only direction that cannot
// destroy their work. A marker from a newer kastor is the exception, since
// ignoring records it does write would be a silent downgrade.
func parseManifest(data []byte) (*manifest, error) {
	m := newManifest()
	versioned := false
	for _, line := range strings.Split(string(data), "\n") {
		fields := strings.Fields(line)
		if len(fields) == 0 || strings.HasPrefix(fields[0], "#") {
			continue
		}
		switch {
		case fields[0] == "kastorbuild" && len(fields) == 2:
			v, err := strconv.Atoi(fields[1])
			if err != nil {
				return newManifest(), nil
			}
			if v > markerVersion {
				return nil, fmt.Errorf("marker version %d was written by a newer kastor; this build understands version %d — upgrade kastor or build into a different directory", v, markerVersion)
			}
			versioned = true
		case len(fields) == 3 && isHash(fields[1]) && keyword(fields[0]) >= 0:
			m.set(fields[2], fields[1], state(keyword(fields[0])))
		default:
			return newManifest(), nil
		}
	}
	if !versioned {
		return newManifest(), nil
	}
	return m, nil
}

// keyword returns the state a marker keyword names, or -1 if it names none.
func keyword(s string) int {
	for i, k := range keywords {
		if k == s {
			return i
		}
	}
	return -1
}

func hashBytes(data []byte) string {
	sum := sha256.Sum256(data)
	return hex.EncodeToString(sum[:])
}

func hashPath(path string) (string, error) {
	data, err := os.ReadFile(path)
	if err != nil {
		return "", err
	}
	return hashBytes(data), nil
}

func isHash(s string) bool {
	if len(s) != hex.EncodedLen(sha256.Size) {
		return false
	}
	_, err := hex.DecodeString(s)
	return err == nil
}
