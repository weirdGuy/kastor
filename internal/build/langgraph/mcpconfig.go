package langgraph

import (
	"encoding/json"
	"fmt"
	"sort"
	"strings"

	"github.com/getkastordev/kastor/internal/schema"
)

// mcpConfigFile is the generated MCP connection config, read by mcp_support
// at call time (SPEC.md §3.3).
const mcpConfigFile = "mcp_servers.json"

// mcpConfigNotice marks the file generated. JSON has no comment syntax, so
// the notice rides in a "//" key — the convention npm and VS Code settings
// files use. The bridge looks a server up by its exact name, so the key is
// never mistaken for one.
const mcpConfigNotice = "Generated by kastor build. Do not edit. Connection config only: " +
	"a credential value never appears here, and neither does the reference naming one (SPEC.md §3.3)."

// mcpTransport maps a spec transport (SPEC.md §3.6) to the langchain-mcp-
// adapters connection transport name.
func mcpTransport(s *schema.MCPServer) (string, error) {
	switch s.Transport {
	case "http":
		return "streamable_http", nil
	case "stdio":
		return "stdio", nil
	}
	return "", fmt.Errorf("%s: unknown transport %q", s.Addr(), s.Transport)
}

// genMCPServers emits mcp_servers.json from the module's mcp_server blocks.
// It holds connection config only: a credential value never appears in it and
// neither does an auth.ref (SPEC.md §3.3). Authentication is injected by the
// generated bridge, which reads the environment in the user's own process at
// call time — see genMCPSupport.
//
// Every declared server is emitted, reachability from an agent not required,
// the same way this target treats an unreferenced model or prompt.
func genMCPServers(servers []*schema.MCPServer) ([]byte, error) {
	var b strings.Builder
	b.WriteString("{\n")
	fmt.Fprintf(&b, "  %s: %s", jsonString("//"), jsonString(mcpConfigNotice))

	for _, s := range servers {
		transport, err := mcpTransport(s)
		if err != nil {
			return nil, err
		}
		b.WriteString(",\n")
		fmt.Fprintf(&b, "  %s: {\n", jsonString(s.Name))
		fmt.Fprintf(&b, "    %s: %s", jsonString("transport"), jsonString(transport))
		switch s.Transport {
		case "http":
			fmt.Fprintf(&b, ",\n    %s: %s", jsonString("url"), jsonString(s.URL))
		case "stdio":
			fmt.Fprintf(&b, ",\n    %s: %s", jsonString("command"), jsonString(s.Command))
			args := make([]string, len(s.Args))
			for i, arg := range s.Args {
				args[i] = jsonString(arg)
			}
			fmt.Fprintf(&b, ",\n    %s: [%s]", jsonString("args"), strings.Join(args, ", "))
		}
		b.WriteString("\n  }")
	}

	b.WriteString("\n}\n")
	return []byte(b.String()), nil
}

// mcpAuthEnv maps server name → environment variable holding its credential,
// for the auth bindings selected on this target (SPEC.md §3.6). Only servers
// a tool actually binds are wired: an unreferenced server is bound nowhere, so
// it gets connection config but nothing to authenticate with.
//
// env:// is the only scheme this target supports; connection:// names a
// credential a platform holds, and there is no platform on the codegen path.
// `kastor validate` rejects that pair before codegen runs — this is the
// generator refusing to emit something it cannot mean, not the primary check.
func mcpAuthEnv(servers []*schema.MCPServer, bound map[string]bool, targetAddr string) (map[string]string, error) {
	env := map[string]string{}
	for _, s := range servers {
		if !bound[s.Name] {
			continue
		}
		auth, ok := s.AuthFor(targetAddr)
		if !ok {
			continue
		}
		scheme, value, err := schema.ParseCredentialRef(auth.Ref)
		if err != nil {
			return nil, fmt.Errorf("%s: %w", s.Addr(), err)
		}
		if scheme != schema.SchemeEnv {
			return nil, fmt.Errorf("%s: auth ref %q cannot be bound on %s; a generated project holds no platform connections — use env://<NAME>",
				s.Addr(), auth.Ref, targetAddr)
		}
		env[s.Name] = value
	}
	return env, nil
}

// sortedAuthEnv renders the auth map in server order, so the generated
// bridge is byte-identical run to run.
func sortedAuthEnv(env map[string]string) [][2]string {
	names := make([]string, 0, len(env))
	for name := range env {
		names = append(names, name)
	}
	sort.Strings(names)

	pairs := make([][2]string, 0, len(names))
	for _, name := range names {
		pairs = append(pairs, [2]string{name, env[name]})
	}
	return pairs
}

// jsonString renders a Go string as a JSON string literal.
func jsonString(s string) string {
	encoded, err := json.Marshal(s)
	if err != nil {
		// json.Marshal of a string fails only on invalid UTF-8, which it
		// replaces rather than rejecting; there is no reachable error here.
		return `""`
	}
	return string(encoded)
}
