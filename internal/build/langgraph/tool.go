// genTool emits tools/<name>.py for one tool block. The interface (params,
// returns) renders the same for every kind — a @tool function with typed
// parameters — while the body is the kind's binding.
func genTool(t *schema.Tool) ([]byte, error) {
	switch t.Source.Kind {
	case "mcp":
		return genMCPTool(t)
	case "http":
		return genHTTPTool(t)
	case "runtime":
		return genRuntimeTool(t)
	case "builtin":
		return nil, fmt.Errorf("%s: source kind \"builtin\" is platform-provided and has no langgraph codegen mapping; use a platform target for it", t.Addr())
	case "script":
		return nil, fmt.Errorf("%s: source kind \"script\" is not supported by the langgraph target yet", t.Addr())
	}
	return nil, fmt.Errorf("%s: unknown source kind %q", t.Addr(), t.Source.Kind)
}

// toolParams builds the generated function's parameter list: params without
// a default first, then defaulted ones, both in declaration order.
func toolParams(t *schema.Tool) ([]pyParam, error) {
	var required, optional []pyParam
	for _, param := range t.Params {
		p := pyParam{
			name:   pyIdent(param.Name),
			source: param.Name,
			hint:   pyType(param.Type),
			doc:    param.Description,
		}
		if param.Default != nil {
			lit, err := pyLiteral(param.Default)
			if err != nil {
				return nil, fmt.Errorf("%s: param %q: %w", t.Addr(), param.Name, err)
			}
			p.def = lit
		}
		if p.def == "" {
			required = append(required, p)
		} else {
			optional = append(optional, p)
		}
	}
	return append(required, optional...), nil
}

// toolSummary is the generated function's docstring summary — the tool
// description when present, since platforms surface it to the model.
func toolSummary(t *schema.Tool) string {
	if t.Description != "" {
		return t.Description
	}
	return "Kastor tool " + t.Addr() + "."
}

// toolHeader emits the module docstring and imports shared by every kind. The
// notice differs for a runtime stub: that one file is the user's to edit, so
// telling them not to would be both wrong and the bug this contract fixes.
func toolHeader(b *strings.Builder, t *schema.Tool, binding string, extraImports ...string) {
	head := t.Addr()
	if t.Description != "" {
		head += " — " + t.Description
	}
	notice := "Generated by kastor build. Do not edit."
	if t.Source.Kind == "runtime" {
		notice = "Generated by kastor build, then yours: kastor writes this stub once\nand keeps whatever you leave here on later builds."
	}
	fmt.Fprintf(b, "\"\"\"%s\n\n%s\n\nBinding: %s\n\"\"\"\n\n", head, notice, binding)
	for _, imp := range extraImports {
		b.WriteString(imp + "\n")
	}
	b.WriteString("\n\n@tool\n")
}

// parseMCPURI splits mcp://<server>/<tool> into its two parts.
func parseMCPURI(t *schema.Tool) (server, tool string, err error) {
	fail := func() (string, string, error) {
		return "", "", fmt.Errorf("%s: source uri %q: expected mcp://<server>/<tool>", t.Addr(), t.Source.URI)
	}
	u, parseErr := url.Parse(t.Source.URI)
	if parseErr != nil || u.Scheme != "mcp" || u.Host == "" {
		return fail()
	}
	tool = strings.TrimPrefix(u.Path, "/")
	if tool == "" || strings.Contains(tool, "/") {
		return fail()
	}
	return u.Host, tool, nil
}

// genMCPTool binds the tool to one tool on one MCP server via the emitted
// mcp_support bridge. The server and tool names come from the source uri;
// how to reach the server comes from its mcp_server block (see genMCPServers).
func genMCPTool(t *schema.Tool) ([]byte, error) {
	server, name, err := parseMCPURI(t)
	if err != nil {
		return nil, err
	}
	params, err := toolParams(t)
	if err != nil {
		return nil, err
	}

	var b strings.Builder
	toolHeader(&b, t,
		fmt.Sprintf("MCP server %q, tool %q (connection config in %s).", server, name, mcpConfigFile),
		"from langchain.tools import tool",
		"",
		"from mcp_support import call_mcp_tool",
	)
	b.WriteString(signature(pyIdent(t.Name), params, pyType(t.Returns.Type)) + "\n")
	b.WriteString(docstring("    ", toolSummary(t), params))
	fmt.Fprintf(&b, "    result = call_mcp_tool(\n        %s,\n        %s,\n        %s,\n    )\n",
		pyString(server), pyString(name), argsDict(params, "        "))

	switch t.Returns.Type {
	case "number":
		b.WriteString("    return float(result)\n")
	case "bool":
		b.WriteString("    return bool(result)\n")
	default:
		b.WriteString("    return str(result)\n")
	}
	return []byte(b.String()), nil
}

// genHTTPTool binds the tool to a REST endpoint: parameters are POSTed as a
// JSON object to the source uri and the response body is coerced to the
// declared return type.
func genHTTPTool(t *schema.Tool) ([]byte, error) {
	u, err := url.Parse(t.Source.URI)
	if err != nil || (u.Scheme != "http" && u.Scheme != "https") || u.Host == "" {
		return nil, fmt.Errorf("%s: source uri %q is not a valid http(s) endpoint", t.Addr(), t.Source.URI)
	}
	params, err := toolParams(t)
	if err != nil {
		return nil, err
	}

	var b strings.Builder
	toolHeader(&b, t,
		fmt.Sprintf("POSTs parameters as JSON to %q.", t.Source.URI),
		"import json",
		"from urllib.request import Request, urlopen",
		"",
		"from langchain.tools import tool",
	)
	b.WriteString(signature(pyIdent(t.Name), params, pyType(t.Returns.Type)) + "\n")
	b.WriteString(docstring("    ", toolSummary(t), params))
	fmt.Fprintf(&b, "    payload = json.dumps(%s, sort_keys=True).encode(\"utf-8\")\n", argsDict(params, "    "))
	fmt.Fprintf(&b, "    request = Request(\n        %s,\n        data=payload,\n        headers={\"Content-Type\": \"application/json\"},\n    )\n", pyString(t.Source.URI))
	b.WriteString("    with urlopen(request) as response:\n        body = response.read().decode(\"utf-8\")\n")

	switch t.Returns.Type {
	case "number":
		b.WriteString("    return float(body)\n")
	case "bool":
		b.WriteString("    return bool(json.loads(body))\n")
	default:
		b.WriteString("    return body\n")
	}
	return []byte(b.String()), nil
}

// stubSidecar is the file name build.Write would use for this tool's sidecar,
// for the stub comment to point at. Derived through build.SidecarFor from the
// same tools/<name>.py path Generate emits, so the comment cannot drift from
// where the sidecar actually appears.
func stubSidecar(t *schema.Tool) string {
	return path.Base(build.SidecarFor(toolPath(t)))
}

// toolPath is the generated file path for one tool, relative to the output
// directory.
func toolPath(t *schema.Tool) string {
	return "tools/" + pyIdent(t.Name) + ".py"
}

// genRuntimeTool emits the stub SPEC.md §3.3 promises for kind "runtime":
// the interface is generated, the body is the user's to supply. The file is
// generated once and preserved after that (see build.File.Preserve).
func genRuntimeTool(t *schema.Tool) ([]byte, error) {
	params, err := toolParams(t)
	if err != nil {
		return nil, err
	}

	var b strings.Builder
	toolHeader(&b, t,
		"runtime stub — the implementation is user code.",
		"from langchain.tools import tool",
	)
	b.WriteString(signature(pyIdent(t.Name), params, pyType(t.Returns.Type)) + "\n")
	b.WriteString(docstring("    ", toolSummary(t), params))
	b.WriteString("    # TODO: implement this runtime tool. This file is yours once you edit it:\n")
	b.WriteString("    # kastor build writes the stub once and then leaves the file alone. If the\n")
	fmt.Fprintf(&b, "    # spec later changes this tool, the new stub lands beside it as\n    # %s and the build says so — reconcile the two and\n    # delete the sidecar.\n", stubSidecar(t))
	fmt.Fprintf(&b, "    raise NotImplementedError(\n        %s\n    )\n",
		pyString(t.Addr()+` (kind = "runtime") has no implementation yet`))
	return []byte(b.String()), nil
}

// genMCPSupport emits mcp_support.py, the synchronous bridge generated MCP
// tools call through. Connection config comes from the generated
// mcp_servers.json; authentication never does. authEnv maps a server name to
// the environment variable its auth ref names (SPEC.md §3.6), read here — in
// the user's own process, at call time — so no credential value has to pass
// through kastor or land in a generated file.
func genMCPSupport(authEnv map[string]string) []byte {
	var b strings.Builder
	b.WriteString(`"""Synchronous bridge from generated tools to MCP servers.

Generated by kastor build. Do not edit.

Connection config comes from ` + mcpConfigFile + `, generated beside this file from
the module's mcp_server blocks. Point KASTOR_MCP_CONFIG at another file to
override it wholesale for one run — a development escape hatch for aiming at a
local server instance, not how connection details are meant to arrive.

Credentials are separate and are never written to a file: a server whose spec
declares an env:// auth ref appears in _AUTH_ENV below, and its token is read
from the environment here, at call time.
"""

import asyncio
import json
import os
from typing import Any

_CONFIG_ENV = "KASTOR_MCP_CONFIG"
_CONFIG_FILE = ` + pyString(mcpConfigFile) + `

# server name -> environment variable holding its bearer token, from each
# server's env:// auth ref. Never the token itself.
`)
	pairs := sortedAuthEnv(authEnv)
	if len(pairs) == 0 {
		b.WriteString("_AUTH_ENV: dict[str, str] = {}\n")
	} else {
		b.WriteString("_AUTH_ENV = {\n")
		for _, pair := range pairs {
			fmt.Fprintf(&b, "    %s: %s,\n", pyString(pair[0]), pyString(pair[1]))
		}
		b.WriteString("}\n")
	}

	b.WriteString(`

def _config_path():
    """Path to the MCP server config: KASTOR_MCP_CONFIG, else the generated file."""
    return os.environ.get(_CONFIG_ENV, _CONFIG_FILE)


def ensure_config() -> None:
    """Fail fast at startup if a KASTOR_MCP_CONFIG override points nowhere.

    Only the override is checked. The default config is generated beside this
    file by kastor build, so its absence means a generated file was deleted —
    rebuild. An override is typed by hand for one run and is worth catching
    before the first tool call fails deep inside it.
    """
    override = os.environ.get(_CONFIG_ENV)
    if override is None or os.path.exists(override):
        return
    raise SystemExit(
        "kastor: MCP server config override not found\n"
        f"  found:    {_CONFIG_ENV}={override!r}, but no file at that path\n"
        "  expected: a langchain-mcp-adapters connection file, keyed by server name\n"
        f"  fix:      point {_CONFIG_ENV} at an existing file, "
        f"or unset it to use the generated {_CONFIG_FILE!r}"
    )


def _connection(server):
    path = _config_path()
    try:
        with open(path, encoding="utf-8") as config:
            servers = json.load(config)
    except FileNotFoundError:
        raise RuntimeError(
            f"MCP server config {path!r} not found; run kastor build, "
            f"or point {_CONFIG_ENV} at a file"
        ) from None
    if server not in servers:
        raise KeyError(f"MCP server {server!r} is not configured in {path!r}")
    return _authenticated(server, servers[server])


def _authenticated(server, connection):
    """Add the server's bearer token, read from the environment at call time."""
    variable = _AUTH_ENV.get(server)
    if variable is None:
        return connection
    token = os.environ.get(variable)
    if not token:
        raise RuntimeError(
            f"kastor: MCP server {server!r} has no credential\n"
            f"  found:    {variable} is unset or empty\n"
            f"  expected: the server's spec declares auth ref env://{variable}\n"
            f"  fix:      export {variable}=<token>"
        )
    connection = dict(connection)
    headers = dict(connection.get("headers") or {})
    headers["Authorization"] = f"Bearer {token}"
    connection["headers"] = headers
    return connection


def _select_tool(server, tool, tools):
    """Return the named tool, or fail listing what the server advertises."""
    for candidate in tools:
        if candidate.name == tool:
            return candidate
    advertised = ", ".join(sorted(candidate.name for candidate in tools)) or "(none)"
    raise RuntimeError(
        f"kastor: MCP server {server!r} does not expose tool {tool!r}\n"
        f"  found:    tool {tool!r} is not on server {server!r}\n"
        f"  expected: one of the tools the server advertises: {advertised}\n"
        f"  fix:      point the tool's spec URI at mcp://{server}/<an advertised tool>"
    )


def call_mcp_tool(server, tool, arguments) -> Any:
    """Call one tool on one MCP server and return its result."""

    async def _call():
        from langchain_mcp_adapters.client import MultiServerMCPClient

        client = MultiServerMCPClient({server: _connection(server)})
        tools = await client.get_tools(server_name=server)
        return await _select_tool(server, tool, tools).ainvoke(arguments)

    return asyncio.run(_call())
`)
	return []byte(b.String())
}
